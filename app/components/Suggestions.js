'use client';
import { useState, useTransition } from 'react';
import { setSuggestion } from '../home-actions';

const CATS = [['business', 'Business'], ['personal', 'Personal'], ['health', 'Health'], ['finance', 'Finance']];

export default function Suggestions({ items, lastDate }) {
  const counts = Object.fromEntries(CATS.map(([k]) => [k, items.filter((i) => i.category === k).length]));
  const first = CATS.find(([k]) => counts[k])?.[0] || 'business';
  const [cat, setCat] = useState(first);
  const [hidden, setHidden] = useState(() => new Set());
  const [, start] = useTransition();
  const [refresh, setRefresh] = useState(null);

  const act = (id, status) => {
    setHidden((h) => new Set(h).add(id));
    start(async () => { try { await setSuggestion(id, status); } catch { setHidden((h) => { const n = new Set(h); n.delete(id); return n; }); } });
  };
  const doRefresh = async () => {
    setRefresh('Asking Claude for fresh suggestions… this runs with the next sync (1–3 min).');
    try {
      const r = await fetch('/api/sync', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ suggestions: true }) }).then((x) => x.json());
      if (!r.ok) setRefresh(r.error || 'Could not start the refresh.');
    } catch { setRefresh('Could not start the refresh.'); }
  };
  const list = items.filter((i) => i.category === cat && !hidden.has(i.id));

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 14 }}>
      <div style={{ display: 'flex', flexWrap: 'wrap', gap: 8, alignItems: 'center' }} role="tablist" aria-label="Suggestion categories">
        {CATS.map(([k, l]) => (
          <button key={k} type="button" role="tab" aria-selected={cat === k} className={`pill${cat === k ? ' active' : ''}`} onClick={() => setCat(k)}>
            {l}{counts[k] ? <span className="pill-count">{counts[k]}</span> : null}
          </button>
        ))}
        <span style={{ flex: 1 }} />
        <button type="button" className="linkbtn" onClick={doRefresh} disabled={!!refresh}>Refresh suggestions</button>
      </div>
      {refresh && <p className="muted" style={{ margin: 0, fontSize: 13 }} aria-live="polite">{refresh}</p>}
      {list.length === 0 ? (
        <p className="empty" style={{ margin: 0 }}>{items.length ? 'No open suggestions in this area.' : 'Suggestions appear after the first sync of the day.'}</p>
      ) : (
        <div className="sugg-grid">
          {list.map((s) => (
            <article key={s.id} className="sugg">
              <div style={{ display: 'flex', gap: 8, alignItems: 'baseline' }}>
                <strong style={{ flex: 1 }}>{s.title}</strong>
                {s.priority === 'high' && <span className="neg" style={{ fontSize: 12 }}>high</span>}
              </div>
              {s.body && <p style={{ margin: 0 }}>{s.body}</p>}
              {s.basis && <p className="muted" style={{ margin: 0, fontSize: 12 }}>Based on: {s.basis}</p>}
              <div style={{ display: 'flex', gap: 8, marginTop: 4 }}>
                <button type="button" className="btn small" onClick={() => act(s.id, 'done')}>Done</button>
                <button type="button" className="btn ghost small" onClick={() => act(s.id, 'dismissed')}>Dismiss</button>
              </div>
            </article>
          ))}
        </div>
      )}
      {lastDate && <p className="muted" style={{ margin: 0, fontSize: 12 }}>Generated by Claude from your email, meetings, tasks and dashboard data · latest {lastDate}</p>}
    </div>
  );
}
